def _entry(date, title, rows, tone=""):
    body = "".join(
        '<div class="clrow"><div class="clk">%s</div><div class="clv">%s</div></div>' % (k, v)
        for k, v in rows)
    return ('<div class="clcard%s"><div class="clhead"><span class="cldate">%s</span>'
            '<b>%s</b></div>%s</div>' % (tone, date, title, body))


